  public getDialogueNode(
    nodeId: string,
    quests: Quest[],
    loreMasterUnlocked = false
  ): DialogueNode | null {
    const resolvedId = nodeId === 'sanctuary_altar_choice' ? 'altar_choice_root' : nodeId;
    return this.getNode(resolvedId, quests, loreMasterUnlocked);
  }

  public getNode(
    nodeId: string,
    quests: Quest[],
    loreMasterUnlocked = false
  ): DialogueNode | null {
    const raw = this.nodes[nodeId];
    if (!raw) return null;

    const filteredOptions = raw.options.filter((opt) => {
      if (opt.requiresLoreMaster && !loreMasterUnlocked) {
        return false;
      }
      if (!opt.conditionQuestId) return true;
      const q = quests.find((item) => item.id === opt.conditionQuestId);
      if (!q) return false;
      if (opt.conditionStatus && q.status !== opt.conditionStatus) return false;
      if (
        opt.conditionStageIndex !== undefined &&
        (q.status !== 'active' || q.currentStageIndex !== opt.conditionStageIndex)
      ) {
        return false;
      }
      return true;
    });

    return {
      ...raw,
      options: filteredOptions,
    };
  }
