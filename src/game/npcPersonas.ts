export function computeRelationshipStage(
  affinity: number,
  romance: number
): {
  stage: NpcRelationshipStage;
  statusTitleRu: string;
} {
  if (romance >= 80 && affinity >= 60) {
    return { stage: 'soulmate', statusTitleRu: '❤️ Истинная Любовь (Влюблён в вас без памяти)' };
  }
  if (romance >= 50 && affinity >= 35) {
    return { stage: 'lover', statusTitleRu: '💕 Возлюбленный (Страстный роман)' };
  }
  if (romance >= 25 && affinity >= 15) {
    return { stage: 'crush', statusTitleRu: '💘 Тайная симпатия и флирт' };
  }
  if (affinity <= -55) {
    return { stage: 'enemy', statusTitleRu: '⚔️ Заклятый враг (Глубокая вражда)' };
  }
  if (affinity <= -20) {
    return { stage: 'rival', statusTitleRu: '⚡ В ссоре (Обида и неприязнь)' };
  }
  if (affinity >= 65) {
    return { stage: 'close_friend', statusTitleRu: '🌟 Лучший друг (Кровное братство)' };
  }
  if (affinity >= 25) {
    return { stage: 'friend', statusTitleRu: '🤝 Добрый друг и союзник' };
  }
  return { stage: 'stranger', statusTitleRu: '🧭 Знакомый собеседник' };
}

export function createInitialRelationshipState(
  persona: NpcPersonaProfile
): NpcRelationshipState {
  const isStreamer = persona.id === 'npc_streamer_foozzee';
  const initialAffinity = isStreamer ? 35 : 10;
  const { stage, statusTitleRu } = computeRelationshipStage(initialAffinity, 0);
  return {
    npcId: persona.id,
    npcName: persona.name,
    affinity: initialAffinity,
    romance: 0,
    trust: isStreamer ? 30 : 10,
    stage,
    statusTitleRu,
    mood: isStreamer ? 'joyful' : 'friendly',
    moodLabelRu: isStreamer ? 'На позитиве · В эфире Twitch' : 'Доброжелательное',
    lastThought: isStreamer
      ? 'Вижу Корвуса! Надо подойти, поздороваться и позвать его к нам на ламповый стрим twitch.tv/foozzee!'
      : `Интересно, с какими мыслями Корвус пожаловал ко мне сегодня?`,
    memories: [],
    turnCount: 0,
  };
}

function pickNonRepeatingLine(
  candidates: string[],
  usedHistoryTexts: string[],
  turnCount: number
): string {
  if (candidates.length === 0) return '';
  const unused = candidates.filter(
    (c) => !usedHistoryTexts.some((h) => h.includes(c.slice(0, 32)))
  );
  if (unused.length > 0) {
    return unused[turnCount % unused.length];
  }
  return candidates[turnCount % candidates.length];
}

